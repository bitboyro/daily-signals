import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const locales = ['en', 'ro'];
const bundles = Object.fromEntries(await Promise.all(locales.map(async (locale) => {
  const source = JSON.parse(await readFile(`${root}locales/${locale}.json`, 'utf8'));
  if (Object.values(source).some((value) => typeof value !== 'string' || value.trim() === '')) {
    throw new Error(`${locale} messages must be non-empty strings`);
  }
  return [locale, source];
})));

const expectedKeys = Object.keys(bundles.en).sort();
for (const locale of locales) {
  const actualKeys = Object.keys(bundles[locale]).sort();
  if (JSON.stringify(actualKeys) !== JSON.stringify(expectedKeys)) {
    throw new Error(`${locale} message keys differ from en`);
  }
}

const output = `// Generated by tools/generate-messages.mjs; edit locales/*.json instead.\n`
  + `export const messages = ${JSON.stringify(bundles, null, 2)} as const;\n\n`
  + `export type Locale = keyof typeof messages;\n`
  + `export type MessageKey = keyof typeof messages.en;\n`;
const target = `${root}src/generated/messages.ts`;

if (process.argv.includes('--check')) {
  const current = await readFile(target, 'utf8').catch(() => '');
  if (current !== output) {
    console.error('generated locale bundle is stale; run npm run locales:generate');
    process.exitCode = 1;
  }
} else {
  await writeFile(target, output);
}
